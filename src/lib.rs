//! # poler-mesh — единый диспетчер POLER Mesh
//!
//! Хаб, который объединяет все узлы POLER-сети (poler-git, poler-engine,
//! будущие почта/диск) под ОДИН MCP-интерфейс и ОДИН токен агента
//! (`POLER_MESH_TOKEN`).
//!
//! Архитектура (анти-p3: минимум движущихся частей):
//!
//! ```text
//!                    ┌─────────────────────────────────────┐
//!   агент ──token──▶ │  poler-mesh (этот бинарник)         │
//!   (CLI/HTTP)       │  tools/list = union всех узлов      │
//!                    │  tools/call → маршрут к узлу        │
//!                    └───────┬──────────┬──────────┬───────┘
//!                       stdio│      stdio│      stdio│
//!                    ┌───────▼──┐ ┌─────▼────┐ ┌───▼──────┐
//!                    │poler-git │ │poler-    │ │ почта/   │
//!                    │(весь гит)│ │engine    │ │ диск ... │
//!                    └──────────┘ │(NLM,web) │ └──────────┘
//!                                 └──────────┘
//! ```
//!
//! Узлы общаются со своими API напрямую (HTTPS/CDP) — никаких
//! git-коммитов как транспорта, никаких общих симметричных секретов.
//! PAT провайдеров остаются внутри своих узлов и наружу не выходят.
//!
//! Хаб может работать сам как узел: `poler-mesh --mcp-stdio` —
//! так один CLI вызывается из другого, сетка вкладывается в сетку.

